@app.get("/health")
def health():
    """Quick health check — also returns chunk count."""
    try:
        count = retriever.count()
        status = "ready" if count > 0 else "no_data"
    except Exception as e:
        return {"status": "error", "detail": str(e)}
    return {"status": status, "chunks_in_db": count}


@app.post("/chat", response_model=ChatResponse)
def chat(req: ChatRequest):
    """
    Main chat endpoint.
    1. Retrieve relevant chunks from ChromaDB
    2. Generate a grounded answer via Azure OpenAI
    3. Store the turn in conversation history
    4. Return answer + full retrieval metadata
    """
    # Resolve or create conversation ID
    conv_id = req.conversation_id or str(uuid.uuid4())
    history = conversation_store.get(conv_id, [])

    # 1. Retrieve
    try:
        chunks = retriever.query(req.message, top_k=req.top_k)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Retrieval error: {e}")

    if not chunks:
        raise HTTPException(
            status_code=404,
            detail="No relevant chunks found. Make sure the PDFs have been ingested.",
        )

    # 2. Generate
    try:
        answer = generator.generate(
            question=req.message,
            chunks=chunks,
            conversation_history=history,
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Generation error: {e}")

    answer = _normalize_malformed_page_tails(answer)
    # Normalize vague source names to concrete PDF filenames for reliable clicking.
    answer = _normalize_multi_source_citations(answer)
    answer = _sanitize_inline_citation_sources(answer, chunks)

    # Ensure the answer includes citations in the required inline format.
    # This also makes evaluation more robust if the model omits the requested citation pattern.
    answer = _ensure_answer_has_citations(answer, chunks)

    # 3. Update history
    history.append({"role": "user", "content": req.message})
    history.append({"role": "assistant", "content": answer})
    conversation_store[conv_id] = history

    # 4. Return
    return ChatResponse(
        answer=answer,
        conversation_id=conv_id,
        sources=[SourceChunk(**c) for c in chunks],
        num_chunks_retrieved=len(chunks),
        model_used=AZURE_OPENAI_DEPLOYMENT,
    )


@app.get("/ingestion-status", response_model=IngestionStatusResponse)
def ingestion_status():
    """Returns which documents are in the vector store and how many chunks total."""
    status = get_ingestion_status()
    return IngestionStatusResponse(
        total_chunks_in_db=retriever.count(),
        ingested_files=status,
    )


@app.delete("/conversation/{conversation_id}")
def delete_conversation(conversation_id: str):
    """Clear conversation history for a given session."""
    if conversation_id in conversation_store:
        del conversation_store[conversation_id]
        return {"message": f"Conversation {conversation_id} cleared."}
    raise HTTPException(status_code=404, detail="Conversation not found.")


@app.get("/conversations")
def list_conversations():
    """List all active conversation IDs and their turn counts."""
    return {
        cid: len(turns) // 2
        for cid, turns in conversation_store.items()
    }
