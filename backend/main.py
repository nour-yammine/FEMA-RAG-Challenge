_CITATION_RE = re.compile(
    r"""
    \(\s*Source:\s*[^,]+
    \s*,\s*Sections?:\s*.*
    \s*,\s*Pages?:\s*\d+(?:\s*,\s*\d+)*
    \s*\)
    """,
    re.IGNORECASE | re.VERBOSE | re.DOTALL,
)


def _safe_citation_section(raw: str) -> str:
    """One line, no commas before Page — keeps frontend citation regex reliable."""
    if not raw:
        return ""
    s = " ".join(str(raw).split())
    return s.replace(",", ";")[:500]


def _format_retrieved_citation(c: dict) -> str:
    # Keep format aligned with generator/system prompt + assessment expectations.
    sec = _safe_citation_section(str(c.get("section", "") or ""))
    return f"(Source: {c.get('source_document','Unknown')}, Section: {sec}, Page: {c.get('page_number',0)})"


def _ensure_answer_has_citations(answer: str, chunks: List[dict]) -> str:
    """
    Ensure the model output includes citations in the required format.

    If the model already produced inline citations, we leave it unchanged.
    Otherwise, append a deterministic 'Sources (retrieved)' block based on retrieval metadata.
    """
    if not answer:
        answer = ""

    if _CITATION_RE.search(answer):
        return answer

    unique = {}
    # Deduplicate while preserving order.
    for c in chunks:
        key = (c.get("chunk_id"), c.get("source_document"), c.get("section"), c.get("page_number"))
        unique[key] = c

    citations = [_format_retrieved_citation(c) for c in unique.values()]
    sources_block = "\n".join(f"- {c}" for c in citations)
    return f"{answer}\n\nSources (retrieved):\n{sources_block}"


def _sanitize_inline_citation_sources(answer: str, chunks: List[dict]) -> str:
    """
    Keep inline citations concrete and clickable by ensuring Source is a real *.pdf name.
    Converts vague forms like:
      (Source: all provided documents and sections, ...)
      (Source: combined from ..., ...)
    """
    if not answer:
        return answer
    fallback = chunks[0].get("source_document", "Unknown.pdf") if chunks else "Unknown.pdf"

    cit_re = re.compile(
        r"\(\s*Source:\s*(?P<source>[^,]+)\s*,\s*Sections?:\s*(?P<section>.*?),\s*Pages?:\s*(?P<pages>[\d\s,]+)\s*\)",
        re.IGNORECASE | re.DOTALL,
    )

    def repl(m: re.Match) -> str:
        raw_source = m.group("source").strip()
        section = _safe_citation_section(m.group("section").strip())
        pages = m.group("pages").strip()

        # If the source contains one or more filenames, keep the first concrete *.pdf.
        pdf = re.search(r"([A-Za-z0-9._-]+\.pdf)", raw_source, flags=re.IGNORECASE)
        source = pdf.group(1) if pdf else fallback
        return f"(Source: {source}, Section: {section}, Pages: {pages})"

    return cit_re.sub(repl, answer)


def _normalize_malformed_page_tails(answer: str) -> str:
    """
    Normalize malformed tails sometimes generated by the LLM:
      (Source: x.pdf, Section: ..., Pages: 6), Page: 1)
    -> (Source: x.pdf, Section: ..., Pages: 6, 1)
    """
    if not answer:
        return answer

    # Case 1: existing Pages: ... then extra ", Page: N)"
    answer = re.sub(
        r"\(Source:\s*([^,]+),\s*Section:\s*(.*?),\s*Pages:\s*([\d\s,]+)\),\s*Page:\s*(\d+)\)",
        r"(Source: \1, Section: \2, Pages: \3, \4)",
        answer,
        flags=re.IGNORECASE | re.DOTALL,
    )
    # Case 2: existing Page: ... then extra ", Page: N)"
    answer = re.sub(
        r"\(Source:\s*([^,]+),\s*Section:\s*(.*?),\s*Page:\s*(\d+)\),\s*Page:\s*(\d+)\)",
        r"(Source: \1, Section: \2, Pages: \3, \4)",
        answer,
        flags=re.IGNORECASE | re.DOTALL,
    )
    return answer


def _normalize_multi_source_citations(answer: str) -> str:
    """
    Convert malformed combined citations like:
      (Source: a.pdf, Section: ..., Page: 6; b.pdf, Section: ..., Page: 56)
    into:
      (Source: a.pdf, Section: ..., Page: 6) (Source: b.pdf, Section: ..., Page: 56)
    """
    if not answer:
        return answer

    # Only inspect parenthesized citation-like spans.
    paren_re = re.compile(r"\(\s*Source:\s*.*?\)", re.IGNORECASE | re.DOTALL)

    seg_re = re.compile(
        r"(?:Source:\s*(?P<source>[^,;]+)\s*,\s*)?"
        r"Sections?:\s*(?P<section>.*?)(?:\s*,\s*Pages?:\s*(?P<pages>[\d\s,]+)|\s*,\s*Page:\s*(?P<page>\d+))\s*$",
        re.IGNORECASE | re.DOTALL,
    )

    def repl(m: re.Match) -> str:
        block = m.group(0)
        # Strip outer parentheses
        inner = block[1:-1].strip()
        if ";" not in inner:
            return block

        parts = [p.strip() for p in inner.split(";") if p.strip()]
        out = []
        last_source = None
        for p in parts:
            mm = seg_re.search(p)
            if not mm:
                continue
            src = (mm.group("source") or last_source or "").strip()
            section = (mm.group("section") or "").strip()
            pages = (mm.group("pages") or mm.group("page") or "").strip()
            if not src or not pages:
                continue
            last_source = src
            # Keep singular/plural by counting page numbers.
            nums = re.findall(r"\d+", pages)
            if len(nums) <= 1:
                out.append(f"(Source: {src}, Section: {section}, Page: {nums[0] if nums else pages})")
            else:
                out.append(f"(Source: {src}, Section: {section}, Pages: {', '.join(nums)})")

        return " ".join(out) if out else block

    return paren_re.sub(repl, answer)


# Static PDF serving for clickable citations
PDF_DIR = Path(__file__).resolve().parent.parent / "pdfs"


@app.get("/pdf/{filename}")
def get_pdf(filename: str):
    safe_name = Path(filename).name
    pdf_path = (PDF_DIR / safe_name).resolve()
    if not pdf_path.exists() or PDF_DIR.resolve() not in pdf_path.parents:
        raise HTTPException(status_code=404, detail="PDF not found")
    return FileResponse(pdf_path, media_type="application/pdf")


